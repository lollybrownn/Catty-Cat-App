    private void loadData(){
        ModelTabel model = (ModelTabel) tableClient.getModel();
        model.setRowCount(0);

        List<ModelComp> list = controller.getAllClient();
        for(ModelComp client : list){
            model.addRow(new Object[]{
                client.getId(),
                client.getNama_pemilik(),
                client.getNama_kucing(),
                client.getNomor_telpon(),
                client.getLama_penitipan(),
                client.getBiaya()
            });
        }
    }

