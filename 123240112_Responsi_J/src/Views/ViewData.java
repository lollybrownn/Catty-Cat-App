    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String namaPemilik = tfPemilik.getText();
        String namaKucing = tfKucing.getText();
        String notelpon = tfTelp.getText();
        
        if (namaPemilik.isEmpty() || namaKucing.isEmpty() || notelpon.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Semua field harus diisi");
            return;
        }
        
        ModelComp client = new ModelComp();
        client.setNama_pemilik(namaPemilik);
        client.setNama_kucing(namaKucing);
        client.setNomor_telpon(notelpon);
        client.setLama_penitipan((Integer) (spinnerLama.getValue()));
        
        loadData();
    }//GEN-LAST:event_btnAddActionPerformed

